def _capsule_name(job_id: str, contract_id: str) -> str:
    return f"capsule-{job_id[:8]}-{contract_id}.zip"


def _requirements_text() -> str:
    spec = _PROJECT_ROOT / DEMO_SPEC_PATH
    if spec.is_file():
        try:
            return spec.read_text(encoding="utf-8")
        except OSError:
            pass
    return "演示需求: 认证、事件与幂等契约 (seeded demo spec)"


def _head_sha(template: DemoVerifyTemplate) -> str:
    repo = _PROJECT_ROOT / DEMO_REPO_PATH
    try:
        proc = subprocess.run(
            ["git", "-C", str(repo), "rev-parse", template["head_ref"]],
            capture_output=True,
            text=True,
            timeout=30,
            check=False,
        )
        if proc.returncode == 0:
            return proc.stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return ""
    return ""


def _contracts_for_certificate(
    template: DemoVerifyTemplate,
) -> list[dict[str, Any]]:
    return [
        {
            "id": c["contract_id_str"],
            "result": c["result"],
            "checker_type": c["checker_type"],
            "expected_behavior": c["expected_behavior"],
            "evidence_ref": c["evidence_ref"],
        }
        for c in template["contracts"]
    ]


def _evidence_digests(contracts: list[dict[str, Any]]) -> list[str]:
    return [
        "sha256:"
        + hashlib.sha256(
            f"{c.get('id', '')}:{c.get('evidence_ref', '')}".encode()
        ).hexdigest()
        for c in contracts
    ]


def _summary_for(template: DemoVerifyTemplate, job_id: str) -> dict[str, Any]:
    findings = [
        {
            "id": str(stable_demo_uuid(f"verify:{template['key']}:finding:{i}")),
            "severity": f["severity"],
            "contract_id": f["contract_id"],
            "confidence": f["confidence"],
            "evidence_type": f["evidence_type"],
            "type": "runtime_diff",
            "location": f["impact_path"][0] if f["impact_path"] else "",
            "description": f["description"],
        }
        for i, f in enumerate(template["findings"])
    ]
    contracts_total = len(template["contracts"])
    passed = sum(1 for c in template["contracts"] if c["result"] == "PASS")
    failed = sum(1 for c in template["contracts"] if c["result"] == "FAIL")
    return {
        "verdict": template["verdict"],
        "contracts_total": contracts_total,
        "matrix_passed": passed,
        "matrix_failed": failed,
        "matrix_unverified": contracts_total - passed - failed,
        "findings": findings,
        "capsules": [
            _capsule_name(job_id, f["contract_id"]) for f in template["findings"]
        ],
        "report_path": "",
        "retrieval_note": "seeded demo data (【演示】)",
        "errors": [],
    }


def _insert_verify_job(
    store: MySQLStore, template: DemoVerifyTemplate, job_id: str,
) -> None:
    store.insert_job(
        {
            "id": job_id,
            "repo_path": DEMO_REPO_PATH,
            "base_ref": template["base_ref"],
            "head_ref": template["head_ref"],
            "spec_path": DEMO_SPEC_PATH,
            "status": template["status"],
            "depth": "FAST",
            "github_check": None,
        }
    )
    for i, contract in enumerate(template["contracts"]):
        store.insert_contract(
            {
                "id": str(stable_demo_uuid(f"verify:{template['key']}:contract:{i}")),
                "job_id": job_id,
                **contract,
            }
        )
    for i, finding in enumerate(template["findings"]):
        finding_id = str(stable_demo_uuid(f"verify:{template['key']}:finding:{i}"))
        store.insert_finding(
            {
                "id": finding_id,
                "job_id": job_id,
                "contract_id": finding["contract_id"],
                "severity": finding["severity"],
                "confidence": finding["confidence"],
                "evidence_type": finding["evidence_type"],
                "impact_path": json.dumps(finding["impact_path"]),
                "capsule_path": _capsule_name(job_id, finding["contract_id"]),
            }
        )
    store.save_job_summary(job_id, _summary_for(template, job_id))


def _write_documents(
    template: DemoVerifyTemplate, job_id: str, reports_dir: Path,
) -> None:
    """Write certificate / rejection notice (real builders; skip if present)."""
    short = job_id[:8]
    if template["verdict"] == "VERIFIED":
        path = reports_dir / f"merge-certificate-{short}.json"
        if path.is_file():
            return
        certificate = issue_certificate(
            repository=DEMO_REPO_PATH,
            commit_sha=_head_sha(template),
            requirements_text=_requirements_text(),
            contracts=_contracts_for_certificate(template),
            evidence_digests=_evidence_digests(_contracts_for_certificate(template)),
        )
        if certificate is None:  # honest: never fabricate a certificate
            return
        reports_dir.mkdir(parents=True, exist_ok=True)
        path.write_text(certificate.to_json(), encoding="utf-8")
        return
    path = reports_dir / f"rejection-notice-{short}.json"
    if path.is_file():
        return
    notice = build_rejection_notice(
        repository=DEMO_REPO_PATH,
        commit_sha=_head_sha(template),
        requirements_text=_requirements_text(),
        contracts=_contracts_for_certificate(template),
        reasons=[f["description"] for f in template["findings"]] or [
            "contracts unverified"
        ],
    )
    reports_dir.mkdir(parents=True, exist_ok=True)
    path.write_text(notice.to_json(), encoding="utf-8")


def _write_capsules(
    template: DemoVerifyTemplate, job_id: str, capsules_dir: Path,
) -> None:
    for finding in template["findings"]:
        name = _capsule_name(job_id, finding["contract_id"])
        path = capsules_dir / name
        if path.is_file():
            continue
        payload = json.dumps(
            {
                "demo": True,
                "job_id": job_id,
                "contract_id": finding["contract_id"],
                "severity": finding["severity"],
                "note": (
                    "演示胶囊 — 由 scripts/seed_demo.py 生成, 未经过真实差分执行"
                ),
                "created_at": datetime.now(UTC).isoformat(),
            },
            ensure_ascii=False,
            indent=2,
        )
        capsules_dir.mkdir(parents=True, exist_ok=True)
        with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as zf:
            zf.writestr("capsule.json", payload)
            zf.writestr("REPLAY.md", _REPLAY_MD)
            zf.writestr("reproduce.ps1", _REPRODUCE_PS1)


def _write_stages(
    template: DemoVerifyTemplate, job_id: str, redis: RedisStore | None,
) -> bool:
    if redis is None:
        return False
    try:
        if not redis.is_ready() or redis.stream_length(job_id) > 0:
            return False
        total = len(template["stages"])
        for i, stage in enumerate(template["stages"]):
            redis.xadd_progress(
                job_id,
                stage["node"],
                "completed",
                message=stage["message"],
                percent=round((i + 1) / total * 100.0, 1),
            )
        return True
    except Exception as exc:  # noqa: BLE001 — stages are optional telemetry
        print(f"[seed] 阶段流写入失败 (Redis): {exc}", file=sys.stderr)
        return False


def _split_sql_statements(sql: str) -> list[str]:
    """Split a migration file on ';' — comment-safe.

    storage/migrations.py splits first and strips comment lines afterwards,
    which turns a ';' inside a full-line comment (0005's rollback note,
    0006's "INSERT-only;" bullet) into a broken SQL fragment on a fresh
    database. Stripping comment lines BEFORE splitting keeps those files
    valid; the seed only ever runs statements from the repo's own
    migrations directory.
    """
    without_comments = "\n".join(
        line for line in sql.splitlines() if not line.strip().startswith("--")
    )
    statements: list[str] = []
    for raw in without_comments.split(";"):
        stmt = raw.strip()
        if stmt:
            statements.append(stmt)
    return statements


def ensure_mysql_schema(store: MySQLStore) -> list[str]:
    """Apply pending versioned migrations; returns the applied file names.

    Uses the exact same migration files and schema_migrations bookkeeping
    as storage.migrations.MigrationRunner (one transaction per migration,
    versions recorded once), with the comment-safe splitter above. The API
    does not migrate at startup, so the seed is the one place in the
    one-command flow that can guarantee a readable schema. Already-applied
    versions are skipped, so re-runs are no-ops and the stock runner later
    agrees with us.
    """
    migrations_dir = _PROJECT_ROOT / "infra" / "mysql" / "migrations"
    with store.connection() as conn:
        conn.cursor().execute(
            "CREATE TABLE IF NOT EXISTS schema_migrations ("
            "version INT PRIMARY KEY, "
            "name VARCHAR(255) NOT NULL, "
            "applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP"
            ") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4"
        )
    with store.connection() as conn:
        cur = conn.cursor()
        cur.execute("SELECT version FROM schema_migrations")
        applied = {int(row["version"]) for row in cur.fetchall()}
    if not migrations_dir.exists():
        return []
    names: list[str] = []
    for path in sorted(migrations_dir.glob("*.sql")):
        head, _, rest = path.name.partition("_")
        try:
            version = int(head)
        except ValueError as exc:
            raise ValueError(
                f"migration filename must start with a number: {path.name}"
            ) from exc
        if version in applied:
            continue
        statements = _split_sql_statements(path.read_text(encoding="utf-8"))
        with store.connection() as conn:
            for stmt in statements:
                conn.cursor().execute(stmt)
            conn.cursor().execute(
                "INSERT INTO schema_migrations (version, name) VALUES (%s, %s)",
                (version, rest),
            )
        names.append(path.name)
    return names


def seed_verify_jobs(
    store: MySQLStore,
    *,
    reports_dir: Path,
    capsules_dir: Path,
    redis: RedisStore | None = None,
) -> tuple[int, int]:
    """Insert demo verify history + artifacts. Returns (created, skipped).

    Applies pending schema migrations first (idempotent, versioned) so the
    API and the dashboard have tables to read. Every write is guarded:
    existing job rows are skipped and artifact files are only created when
    missing, so re-runs never duplicate.
    """
    ensure_mysql_schema(store)
    created = 0
    skipped = 0
    for template in demo_verify_templates():
        job_id = stable_demo_uuid(f"verify:{template['key']}")
        if store.get_job(job_id) is None:
            _insert_verify_job(store, template, job_id)
            created += 1
        else:
            skipped += 1
        _write_documents(template, job_id, reports_dir)
        _write_capsules(template, job_id, capsules_dir)
        _write_stages(template, job_id, redis)
    return created, skipped


