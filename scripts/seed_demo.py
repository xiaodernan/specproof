def _print_summary(stats: dict[str, Any], warnings: list[str], note: str) -> None:
    print(
        "[seed] 验证任务(演示历史): "
        f"新建 {stats['verify_created']}, 已存在 {stats['verify_skipped']} "
        "(存储: MySQL — 与 API 相同)"
    )
    print(
        f"[seed] Agent 任务: {stats['agent_job_id']} {SEED_AGENT_TASK_NAME} "
        f"— {note} — 状态: AWAITING_APPROVAL"
    )
    for warning in warnings:
        print(f"[seed] 警告: {warning}")


def main(argv: list[str] | None = None) -> int:
    import os

    args = build_parser().parse_args(argv)
    api_base: str = args.api_base
    api_key: str = args.api_key or os.getenv("SPECPROOF_API_KEY", "").strip()
    agent_url: str = args.agent_store_url or os.getenv(
        "SPECPROOF_AGENT_JOBS_URL", ""
    ).strip()

    warnings: list[str] = []
    stats: dict[str, Any] = {
        "verify_created": 0,
        "verify_skipped": 0,
        "agent_job_id": "",
        "agent_created": False,
    }

    # 1) Verify history — MySQL only, the same store the API reads.
    try:
        mysql = MySQLStore()
        if mysql.is_ready():
            stats["verify_created"], stats["verify_skipped"] = seed_verify_jobs(
                mysql,
                reports_dir=_PROJECT_ROOT / "reports",
                capsules_dir=_PROJECT_ROOT / "capsules",
                redis=RedisStore(),
            )
        else:
            warnings.append("MySQL 未就绪 — 跳过验证任务演示数据 (仅 Agent 任务)")
    except Exception as exc:  # noqa: BLE001 — degrade honestly, never break start
        warnings.append(f"验证任务播种失败: {exc}")

    # 2) Agent demo job — POST when the API is up, durable store always.
    try:
        store = build_agent_store(agent_url)
        if api_key and api_base:
            job_id, created, note = seed_agent_job_via_api(api_base, api_key, store)
        else:
            job, created = seed_agent_job_in_store(store)
            job_id = job.id
            note = "store-only seeding (未配置 API key/base)"
        stats["agent_job_id"] = job_id
        stats["agent_created"] = created
    except Exception as exc:  # noqa: BLE001
        print(f"[seed] Agent 任务播种失败: {exc}", file=sys.stderr)
        warnings.append(f"Agent 任务播种失败: {exc}")
        note = "failed"

    _print_summary(stats, warnings, note)
    return 0


if __name__ == "__main__":
    sys.exit(main())
