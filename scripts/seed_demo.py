def build_agent_store(url: str) -> AgentJobStore:
    """Mirror api/routes/agent_console.py backend selection (fail closed)."""
    target = url.strip()
    if not target:
        return InMemoryAgentJobStore()
    if target.startswith("sqlite:"):
        store: AgentJobStore = SqliteAgentJobStore(target[len("sqlite:"):])
    elif target.startswith(("mysql://", "mysql+pymysql://")):
        store = MySqlAgentJobStore(target)
    else:
        raise ValueError(
            "SPECPROOF_AGENT_JOBS_URL must be '', 'sqlite:<path>' or a "
            f"mysql:// URL (got {url!r}) — refusing to pick an unknown "
            "agent job store backend"
        )
    store.ensure_schema()
    return store


def find_agent_job_by_spec_digest(
    store: AgentJobStore, spec_text: str,
) -> AgentJob | None:
    """The durable idempotency key for the agent seed: sha256(spec_text)."""
    digest = compute_spec_digest(spec_text)
    for job in store.list(limit=500):
        if job.spec_digest == digest:
            return job
    return None


def demo_agent_plan() -> dict[str, Any]:
    """Deep copy of the demo plan with a fresh created_at timestamp."""
    plan = cast(dict[str, Any], json.loads(json.dumps(SEED_AGENT_PLAN)))
    plan["created_at"] = datetime.now(UTC).isoformat()
    return plan


def attach_agent_plan(
    store: AgentJobStore, job_id: str, plan: dict[str, Any],
) -> bool:
    """Attach the demo plan unless one exists or the job is terminal."""
    job = store.get(job_id)
    if job is None or job.plan_json is not None:
        return False
    if job.status in TERMINAL_JOB_STATUSES:
        return False
    try:
        store.set_plan(job_id, plan)
    except InvalidJobTransitionError:
        return False
    return True


