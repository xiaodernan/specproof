        f"- Repo: `{results['repo_root']}`",
        f"- Capsules dir: `{results['capsules_dir']}`",
        f"- Temp worktree: `{worktree['mechanism']}`" + (
            f" (`{worktree['path']}`)" if worktree["path"] else ""
        ),
        f"- Limit: {results['limit'] if results['limit'] is not None else 'none (full run)'}",
        "",
        "## Replay success rate",
        "",
        "| metric | value |",
        "|---|---|",
        f"| capsules enumerated | {totals['enumerated']} |",
        f"| same_conclusion | {totals['same_conclusion']} |",
