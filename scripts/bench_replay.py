        "and/or the deterministic checker that produced the recorded finding must "
        "re-derive it from the head tree. A runtime replay can never reproduce a "
        "static finding, so a runtime COMPLIANT verdict is expected and is not a "
        "contradiction. Verified static evidence is same_conclusion; unverifiable "
        "evidence is replay_failed with the real reason (e.g. the snippet is gone "
        "from head).",
        "- `static_verified` counts only tier-2 successes; the raw "
        "`same_conclusion` count is unchanged, so both numbers stay auditable.",
        "",
        "## Environment",
        "",
        "| tool | status |",
        "|---|---|",
        f"| python | `{env['python']}` |",
        f"| git | `{env['git'] or 'MISSING'}` |",
        f"| pwsh | `{env['pwsh'] or 'MISSING'}` |",
        f"| bash | `{env['bash'] or 'MISSING'}` |",
        f"| java | `{env['java'] or 'MISSING'}` ({env['java_version'] or 'no version line'}) |",
        f"| Maven distribution cache | `{env['maven_dist_cache'] or 'MISSING'}` |",
