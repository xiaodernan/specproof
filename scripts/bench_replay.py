def canonical_manifest_digest(manifest: dict[str, Any]) -> str:
    """Recompute manifest_digest with create_capsule's canonical rule.

    The digest is sha256 over the canonical serialization of the manifest
    WITHOUT the digest field (sorted keys, no whitespace) — the same rule
    agent/nodes/create_capsule.py uses, so any stored copy can be verified.
    """
    without_digest = {k: v for k, v in manifest.items() if k != "manifest_digest"}
    canonical = json.dumps(without_digest, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(canonical.encode()).hexdigest()


def read_zip_json(zip_path: Path, member: str) -> dict[str, Any] | None:
    """Read one JSON member of a capsule zip, or None when absent."""
    try:
        with zipfile.ZipFile(zip_path, "r") as archive:
            if member not in archive.namelist():
                return None
            loaded = json.loads(archive.read(member))
            return loaded if isinstance(loaded, dict) else None
    except (zipfile.BadZipFile, json.JSONDecodeError, OSError):
        return None


def read_zip_text(zip_path: Path, member: str) -> str:
    """Read one text member of a capsule zip; '' when absent or broken."""
    try:
        with zipfile.ZipFile(zip_path, "r") as archive:
            if member not in archive.namelist():
                return ""
            return archive.read(member).decode("utf-8", "replace").strip()
    except (zipfile.BadZipFile, OSError):
        return ""


def read_zip_members(zip_path: Path) -> list[str] | None:
    """The member name list of a zip, or None when the zip is corrupt."""
    try:
        with zipfile.ZipFile(zip_path, "r") as archive:
            return list(archive.namelist())
    except (zipfile.BadZipFile, OSError):
        return None


def collect_store_inventory(
    store: ObjectMetadataStore, capsules_dir: Path,
) -> dict[str, Any]:
    """Summarize the capsule records of the object-metadata store.

    Records are grouped by where their path_hint points: under this repo's
    capsules/ (this_repo), an existing path elsewhere (other_repo), or a
    path that no longer exists (orphan). Joined records are those whose
    payload digest matches a capsule zip under capsules_dir.
    """
    digest_to_records: dict[str, list[ObjectMetadata]] = {}
    total = 0
    this_repo = 0
    other_repo = 0
    orphan = 0
    for record in store.by_kind("capsule"):
        total += 1
        hint = Path(record.path_hint) if record.path_hint else None
        digest = normalize_payload_digest(record.digests.get("payload_sha256", ""))
        digest_to_records.setdefault(digest, []).append(record)
        if hint is None or not hint.exists():
            orphan += 1
        elif capsules_dir.resolve() in hint.resolve().parents:
            this_repo += 1
        else:
            other_repo += 1
    joined = 0
    for zip_path in sorted(capsules_dir.glob("capsule-*.zip")):
        digest = normalize_payload_digest(payload_sha256_of_file(zip_path))
        joined += len(digest_to_records.get(digest, []))
    return {
        "capsule_records_total": total,
        "this_repo_paths": this_repo,
        "other_repo_paths": other_repo,
        "orphan_paths": orphan,
        "joined_to_zip_digests": joined,
    }


def enumerate_capsules(
    capsules_dir: Path, store: ObjectMetadataStore | None,
) -> tuple[list[CapsuleUnit], dict[str, Any]]:
    """Enumerate replay units: zips, extracted dirs and store records.

    A unit is keyed by capsule name (the zip stem). Store records join a
    unit when their payload digest equals the zip's payload digest, which
    is content identity rather than path inference. Extracted capsule
    directories without a matching zip become zip-less units that the
    replay path cannot consume.
    """
    store = store if store is not None else default_object_metadata_store()
    try:
        inventory = collect_store_inventory(store, capsules_dir)
        digest_records: dict[str, list[ObjectMetadata]] = {}
        for record in store.by_kind("capsule"):
            digest = normalize_payload_digest(record.digests.get("payload_sha256", ""))
            if _SHA256_HEX_RE.fullmatch(digest):
                digest_records.setdefault(digest, []).append(record)

        units: list[CapsuleUnit] = []
        zip_paths = sorted(capsules_dir.glob("capsule-*.zip"))
        for zip_path in zip_paths:
            name = zip_path.stem
            sha256 = payload_sha256_of_file(zip_path)
            records = digest_records.get(sha256, [])
            seen: set[str] = set()
            unique_records: list[ObjectMetadata] = []
            for record in records:
                if record.object_id not in seen:
                    seen.add(record.object_id)
                    unique_records.append(record)
            dir_path = capsules_dir / name
            units.append(
                CapsuleUnit(
                    name=name,
                    zip_path=zip_path,
                    dir_path=dir_path if dir_path.is_dir() else None,
                    store_records=tuple(unique_records),
                    sha256=sha256,
                    base_ref=read_zip_text(zip_path, "fixtures/base-ref.txt"),
                    head_ref=read_zip_text(zip_path, "fixtures/head-ref.txt"),
                )
            )
        for dir_path in sorted(capsules_dir.glob("capsule-*")):
            if not dir_path.is_dir():
                continue
            if any(unit.name == dir_path.name for unit in units):
                continue
            units.append(
                CapsuleUnit(
                    name=dir_path.name,
                    zip_path=None,
                    dir_path=dir_path,
                    store_records=(),
                    sha256="",
                    base_ref="",
                    head_ref="",
                )
            )
        return units, inventory
    finally:
        if store is not None:
            store.close()


def verify_evidence(unit: CapsuleUnit) -> EvidenceReport:
    """Verify the capsule's recorded evidence without executing anything.

    Checks: zip payload present and readable; manifest.json present (the
    existing replay path rejects capsules without one); manifest_digest
    recomputes to the recorded value; manifest/finding evidence_digest
    agreement; extracted directory copy agreement; metadata-store payload
    digest agreement.
    """
    problems: list[str] = []
    zip_path = unit.zip_path
    if zip_path is None:
        problems.append(
            "no capsule .zip payload — the replay path cannot consume an extracted layout"
        )
        return EvidenceReport(tuple(problems))
    if read_zip_members(zip_path) is None:
        problems.append("corrupt zip payload (cannot be opened)")
        return EvidenceReport(tuple(problems))
    manifest = read_zip_json(zip_path, "manifest.json")
    if manifest is None:
        problems.append(
            "manifest.json missing — the existing replay path rejects the capsule "
            "as corrupt; recorded evidence cannot be established"
        )
        return EvidenceReport(tuple(problems))
    recorded = str(manifest.get("manifest_digest") or "")
    recomputed = canonical_manifest_digest(manifest)
    if normalize_payload_digest(recorded) != recomputed:
        problems.append(
            f"manifest_digest mismatch: recorded {recorded[:12]!r}..., recomputed "
            f"{recomputed[:12]}... — the manifest was modified after recording"
        )
    finding = read_zip_json(zip_path, "finding.json")
    manifest_evidence = str(manifest.get("evidence_digest") or "")
    finding_evidence = str((finding or {}).get("evidence_digest") or "")
    if (
        manifest_evidence
        and finding_evidence
        and normalize_payload_digest(manifest_evidence)
        != normalize_payload_digest(finding_evidence)
    ):
        problems.append(
            f"evidence_digest disagreement: manifest {manifest_evidence[:12]!r}... "
            f"vs finding {finding_evidence[:12]!r}..."
        )
    if unit.dir_path is not None:
        dir_manifest_path = unit.dir_path / "manifest.json"
        try:
            dir_manifest = json.loads(dir_manifest_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            dir_manifest = None
        if dir_manifest is None:
            problems.append(
                "extracted capsule directory exists but its manifest.json is unreadable"
            )
        elif dir_manifest != manifest:
            problems.append("extracted capsule directory manifest differs from the zip manifest")
    for record in unit.store_records:
        recorded_digest = normalize_payload_digest(record.digests.get("payload_sha256", ""))
        if recorded_digest != unit.sha256:
            problems.append(
                f"object-metadata store record {record.object_id[:8]} records payload "
                f"{recorded_digest[:12]}... but the zip payload hashes to {unit.sha256[:12]}... "
                "— the capsule was modified after it was recorded"
            )
    return EvidenceReport(tuple(problems))


def recorded_claim(manifest: dict[str, Any]) -> dict[str, Any]:
    """The recorded blocker_check conditions, tolerating missing fields."""
    blocker_check = manifest.get("blocker_check") or {}
    conditions = blocker_check.get("blocker_conditions") or {}
    return {
        "2_base_head_execution": bool(conditions.get("2_base_head_execution")),
        "4_db_behavior_evidence": bool(conditions.get("4_db_behavior_evidence")),
        "5_capsule_replayable": bool(conditions.get("5_capsule_replayable")),
    }


def expected_verdict_for(manifest: dict[str, Any]) -> str:
    """The verdict the capsule's recorded evidence commits to."""
    claim = recorded_claim(manifest)
    if claim["2_base_head_execution"]:
        return VERDICT_CONFIRMED
    return NO_RUNTIME_CLAIM


def parse_verdict(output: str) -> str | None:
    """Parse the run script's verdict marker, or None."""
    match = _VERDICT_RE.search(output)
    if match is None:
        return None
    return match.group(1)


def parse_exit_codes(output: str) -> tuple[int | None, int | None]:
    """Parse the Base/Head maven test exit codes printed by the run script."""
    base_exit: int | None = None
    head_exit: int | None = None
    for match in _EXIT_CODE_RE.finditer(output):
        value = int(match.group(2))
        if match.group(1) == "Base":
            base_exit = value
        else:
            head_exit = value
    return base_exit, head_exit


def env_failure_reason(output: str) -> str:
    """The environment failure this output proves, or ''."""
    for pattern, reason in _ENV_FAILURE_PATTERNS:
        if re.search(pattern, output):
            return reason
    return ""


def classify_replay(expected: str, run: RunResult) -> ReplayOutcome:
    """Classify one executed replay against the capsule's recorded claim."""
    output = run.stdout + "\n" + run.stderr
    base_exit, head_exit = parse_exit_codes(output)
    verdict = parse_verdict(output)
    env_reason = env_failure_reason(output)
    if run.error:
        reason = f"run script could not be executed: {run.error}"
        return ReplayOutcome(OUTCOME_ENV, reason, None, None, None)
    if run.timed_out:
        reason = f"run script timed out (limit {DEFAULT_TIMEOUT_S:.0f}s)"
        return ReplayOutcome(OUTCOME_FAILED, reason, verdict, base_exit, head_exit)
    if env_reason and verdict != VERDICT_CONFIRMED:
        suffix = f" — run script verdict {verdict}" if verdict else ""
        return ReplayOutcome(OUTCOME_ENV, env_reason + suffix, verdict, base_exit, head_exit)
    if verdict is None:
        if run.exit_code != 0:
            tail = output.strip().splitlines()[-3:]
            reason = (
                f"run script exited {run.exit_code} without a verdict — "
                f"output tail: {' | '.join(tail)}"
            )
        else:
            reason = "run script produced no verdict"
        return ReplayOutcome(OUTCOME_FAILED, reason, None, base_exit, head_exit)
    if verdict == VERDICT_CONFIRMED:
        if expected == VERDICT_CONFIRMED:
            reason = (
                "recorded base_pass_head_fail reproduced — run script verdict "
                "REGRESSION CONFIRMED"
            )
        else:
            reason = (
                "static-only recorded evidence; runtime replay additionally confirmed the "
                "regression (verdict REGRESSION CONFIRMED) — same conclusion, stronger evidence"
            )
        return ReplayOutcome(OUTCOME_SAME, reason, verdict, base_exit, head_exit)
    if expected == VERDICT_CONFIRMED:
        reason = (
            f"recorded base_pass_head_fail NOT reproduced — run script verdict {verdict} "
            f"(base_exit={base_exit}, head_exit={head_exit})"
        )
    else:
        reason = (
            f"static-only recorded evidence; runtime verdict {verdict} does not reproduce "
            "the finding"
        )
    return ReplayOutcome(OUTCOME_FAILED, reason, verdict, base_exit, head_exit)


