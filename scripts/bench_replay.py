        "",
        "- Tier 1 — runtime reproduction: capsules whose recorded evidence is "
        "runtime (blocker_check 2_base_head_execution=true) claim a base-pass/"
        "head-fail regression; only a run script verdict of REGRESSION CONFIRMED "
        "is same_conclusion.",
        "- Tier 2 — static re-verification: capsules whose recorded evidence kind "
        "is static-only (java_source_diff, openapi_endpoint, constitution_check, "
