"""Full capsule replay batch runner — real replay success rate (主计划 §5.9 / 阶段2).

Enumerates every capsule under capsules/ (zip payloads, extracted capsule
directories and the object-metadata store), replays each one through the
existing replay path (cli/specproof/commands/replay.py) inside a throwaway
git worktree, and classifies the outcome into exactly one of four buckets:

  same_conclusion        the capsule's recorded conclusion was reproduced
  env_mismatch           replay cannot run in this environment: no pwsh/bash
                         executor, no git, missing base/head refs, Maven
                         distribution/dependency download blocked, Docker
                         required — always with the exact reason, never faked
  evidence_inconsistent  the capsule's recorded evidence does not verify:
                         manifest.json missing/unreadable, manifest_digest
                         recompute mismatch, evidence_digest disagreement,
                         metadata-store payload digest mismatch
  replay_failed          replay ran but did not reproduce the conclusion:
                         run script failure, no verdict, or a verdict that
                         contradicts the recorded evidence

Verdict semantics. The capsule records its own claim in the blocker_check
blocker conditions. When 2_base_head_execution is true the capsule claims a
differential regression (base side green, head side red), so only a run script verdict of
"REGRESSION CONFIRMED" is the same conclusion. Capsules whose recorded
evidence is static-only carry no runtime claim; a runtime confirmation still
counts as the same conclusion (it strengthens it), but any other verdict
does not reproduce the finding and is reported as replay_failed.

The run scripts are executed unmodified, exactly as generated by
agent/nodes/create_capsule.py — observed replay defects are reported in the
reasons, never patched around.

Outputs (overwritten on every run):
  docs/eval/replay-results.json — machine-readable results
  docs/eval/replay-results.md   — human-readable summary with success rate

Usage:
  python scripts/bench_replay.py                 # full run, all capsules
  python scripts/bench_replay.py --limit 3       # smoke run, first 3 capsules
  python scripts/bench_replay.py --keep-worktree # keep the temp worktree
"""
