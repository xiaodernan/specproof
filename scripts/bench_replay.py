"""Full capsule replay batch runner — real replay success rate (主计划 §5.9 / 阶段2).

Enumerates every capsule under capsules/ (zip payloads, extracted capsule
directories and the object-metadata store), replays each one through the
existing replay path (cli/specproof/commands/replay.py) inside a throwaway
git worktree, and classifies the outcome into exactly one of four buckets:

  same_conclusion        the capsule's recorded conclusion was reproduced
  env_mismatch           replay cannot run in this environment: no pwsh/bash
                         executor, no git, missing base/head refs, Maven
                         distribution/dependency download blocked, Docker
                         required — always with the exact reason, never faked
  evidence_inconsistent  the capsule's recorded evidence does not verify:
                         manifest.json missing/unreadable, manifest_digest
                         recompute mismatch, evidence_digest disagreement,
                         metadata-store payload digest mismatch
  replay_failed          replay ran but did not reproduce the conclusion:
                         run script failure, no verdict, a verdict that
                         contradicts the recorded evidence, or recorded
                         static evidence that could not be re-verified at
                         the recorded head commit

Verdict semantics (two-tier replay). The capsule records its own claim in
the blocker_check blocker conditions. When 2_base_head_execution is true the
capsule claims a differential regression (base side green, head side red),
so only a run script verdict of "REGRESSION CONFIRMED" is the same
conclusion (tier 1: runtime reproduction).

Capsules whose recorded evidence kind is static-only (java_source_diff,
openapi_endpoint, constitution_check, static_regex_analysis,
probe_differential, mutation/annotation checks — see is_static_evidence_kind)
carry no runtime claim: a Maven base/head run can never reproduce a static
finding, and a runtime COMPLIANT verdict is expected rather than a
contradiction. Their replay is tier 2: static re-verification at the
recorded head commit inside the temp worktree — the recorded snippet paths
exist with the recorded content at head, and/or the deterministic checker
that produced the recorded finding re-derives it from the head tree.
Verified findings are same_conclusion with a static note; unverifiable
findings are replay_failed with the real reason (e.g. the snippet is gone
from head). Static re-verifications are counted separately as
static_verified so the raw same_conclusion count stays auditable. A runtime
confirmation of a static-only capsule additionally counts as the same
conclusion (it strengthens it), but any other runtime verdict does not
reproduce the finding and is reported as replay_failed.

The run scripts are executed unmodified, exactly as generated by
agent/nodes/create_capsule.py — observed replay defects are reported in the
reasons, never patched around.

Outputs (overwritten on every run):
  docs/eval/replay-results.json — machine-readable results
  docs/eval/replay-results.md   — human-readable summary with success rate

Usage:
  python scripts/bench_replay.py                 # full run, all capsules
  python scripts/bench_replay.py --limit 3       # smoke run, first 3 capsules
  python scripts/bench_replay.py --keep-worktree # keep the temp worktree
"""
