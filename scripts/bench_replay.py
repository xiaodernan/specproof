def is_static_evidence_kind(evidence_type: str) -> bool:
    """Whether an evidence kind can only ever be verified statically.

    A runtime base/head execution can never reproduce a static finding: the
    recorded evidence is a source/contract check at the recorded head
    commit, so the honest replay re-verifies it there instead.
    """
    normalized = evidence_type.strip().lower()
    if not normalized:
        return False
    if normalized in STATIC_EVIDENCE_KINDS:
        return True
    return any(token in normalized for token in STATIC_EVIDENCE_KIND_TOKENS)


def is_static_only_capsule(manifest: dict[str, Any]) -> bool:
    """A capsule whose recorded evidence is static-only: its kind is a static
    evidence kind and its recorded claim carries no runtime requirement.

    When the evidence kind is static but the recorded claim still sets
    2_base_head_execution=true, the runtime claim wins and the capsule is
    replayed through tier 1.
    """
    evidence_type = str(manifest.get("evidence_type") or "")
    return (
        is_static_evidence_kind(evidence_type)
        and expected_verdict_for(manifest) == NO_RUNTIME_CLAIM
    )


def read_static_snippets(zip_path: Path | None) -> tuple[tuple[str, str], ...]:
    """Recorded snippet payloads from the optional static-evidence.json member.

    Shape: {"snippets": [{"path": "<posix rel path>", "content": "<text>"}, ...]}.
    Capsules recorded before this member existed carry no snippet payload;
    their evidence is re-verified by re-running the deterministic checkers
    that produced it (see rederive_static_findings).
    """
    if zip_path is None:
        return ()
    payload = read_zip_json(zip_path, "static-evidence.json")
    if payload is None:
        return ()
    raw = payload.get("snippets")
    if not isinstance(raw, list):
        return ()
    snippets: list[tuple[str, str]] = []
    for item in raw:
        if not isinstance(item, dict):
            continue
        path = str(item.get("path") or "").strip()
        content = item.get("content")
        if path and isinstance(content, str):
            snippets.append((path, content))
    return tuple(snippets)


def recorded_static_paths(finding: dict[str, Any] | None) -> list[str]:
    """The snippet paths named by the recorded static evidence.

    Paths come from the recorded finding's location plus any source/resource
    path tokens inside its description (e.g. "... publish count increased in
    com/specproof/demo/service/OrderService.java: 1 -> 2").
    """
    paths: list[str] = []
    if finding is None:
        return paths
    location = str(finding.get("location") or "").strip()
    if location and location.lower() != "none":
        paths.append(location)
    description = str(finding.get("description") or "")
    for match in _RECORDED_PATH_RE.findall(description):
        candidate = match.strip(".,;:)")
        if candidate and candidate not in paths:
            paths.append(candidate)
    return paths


def snapshot_worktree_sources(repo: Path) -> WorktreeSnapshot:
    """Read one checked-out ref's sources exactly as the checkers consume them.

    Java files are keyed by their posix path relative to src/main/java or
    src/test/java; schema.sql is captured as a raw string ('' when absent).
    """
    java: dict[str, str] = {}
    tests: dict[str, str] = {}
    for root, target in (
        (repo / "src" / "main" / "java", java),
        (repo / "src" / "test" / "java", tests),
    ):
        if not root.is_dir():
            continue
        for path in root.rglob("*.java"):
            if not path.is_file():
                continue
            try:
                target[path.relative_to(root).as_posix()] = path.read_text(
                    encoding="utf-8"
                )
            except OSError:
                continue
    schema_path = repo / "src" / "main" / "resources" / "schema.sql"
    try:
        schema_sql = schema_path.read_text(encoding="utf-8")
    except OSError:
        schema_sql = ""
    return WorktreeSnapshot(java=java, tests=tests, schema_sql=schema_sql)


def checkout_worktree_ref(repo: Path, ref: str) -> str:
    """Check out one recorded ref in the temp worktree; '' when it worked."""
    result = subprocess.run(
        ["git", "-C", str(repo), "checkout", "--quiet", "-f", ref],
        capture_output=True, text=True, timeout=300, check=False,
    )
    if result.returncode == 0:
        return ""
    return (result.stderr or result.stdout).strip()[:300]


def resolve_recorded_path(head: WorktreeSnapshot, recorded: str) -> str | None:
    """Resolve a recorded snippet path against the head snapshot.

    Returns the canonical key present in the head snapshot (a java file, a
    test file or schema.sql), or None when the recorded path is gone.
    """
    candidates = (
        recorded,
        "src/main/java/" + recorded,
        "src/test/java/" + recorded,
    )
    for candidate in candidates:
        if candidate in head.java or candidate in head.tests:
            return candidate
    if recorded.endswith("schema.sql") and head.schema_sql:
        return "src/main/resources/schema.sql"
    matches = [
        key
        for key in [*head.java, *head.tests]
        if key.endswith("/" + recorded) or key == recorded
    ]
    if len(matches) == 1:
        return matches[0]
    return None


def recorded_path_content(head: WorktreeSnapshot, key: str) -> str:
    """The head content for one resolved recorded path ('' when unknown)."""
    if key in head.java:
        return head.java[key]
    if key in head.tests:
        return head.tests[key]
    if key == "src/main/resources/schema.sql":
        return head.schema_sql
    return ""


def _normalize_snippet(text: str) -> str:
    """Compare snippets modulo CRLF line endings and trailing whitespace."""
    return text.replace("\r\n", "\n").rstrip()


def rederive_static_findings(
    evidence_type: str,
    contract: dict[str, Any] | None,
    base: WorktreeSnapshot,
    head: WorktreeSnapshot,
) -> tuple[list[dict[str, Any]], str]:
    """Re-run the deterministic checkers that produced the recorded kind.

    Returns (fresh findings at the recorded base/head refs, error). The
    error is non-empty when the recorded kind cannot be re-derived offline —
    recorded honestly, never patched around.
    """
    from agent.checkers.constitution import check_forbidden_changes
    from agent.checkers.java_source import run_contract_checks
    from agent.checkers.schema_and_tests import (
        check_schema_sql,
        check_test_weakening,
    )

    findings: list[dict[str, Any]] = []
    if "constitution" in evidence_type:
        contract_id = str((contract or {}).get("id") or "")
        clauses = list((contract or {}).get("forbidden_changes") or [])
        if not clauses:
            return [], (
                "capsule records constitution_check evidence but its contract "
                "payload carries no forbidden_changes — cannot re-verify statically"
            )
        findings.extend(check_forbidden_changes(
            base.java, head.java, clauses, contract_id,
        ))
        return findings, ""
    if any(
        token in evidence_type
        for token in (
            "java_source_diff", "openapi", "static", "mutation", "annotation", "probe",
        )
    ):
        findings.extend(run_contract_checks(base.java, head.java))
        findings.extend(
            check_schema_sql(base.schema_sql, head.schema_sql, base.java, head.java)
        )
        findings.extend(check_test_weakening(base.tests, head.tests))
        return findings, ""
    return [], (
        f"recorded evidence kind {evidence_type!r} has no deterministic static "
        "checker — cannot re-verify statically"
    )


def classify_static_replay(
    unit: CapsuleUnit,
    manifest: dict[str, Any],
    finding: dict[str, Any] | None,
    contract: dict[str, Any] | None,
    base: WorktreeSnapshot,
    head: WorktreeSnapshot,
) -> ReplayOutcome:
    """Re-verify a static-only capsule's recorded evidence at the head ref.

    Verification methods, in order:
    1. Recorded snippet payloads (static-evidence.json): every recorded
       path must exist at head with the recorded content.
    2. Recorded path presence: every path named by the recorded finding
       (location/description) must still exist in the head tree.
    3. Deterministic checker re-derivation: the checker that produced the
       recorded evidence must re-derive the recorded finding at head.

    Anything unverifiable is replay_failed with the real reason — a
    verification is never fabricated.
    """
    head_ref = unit.head_ref or "<none>"
    if finding is None:
        return ReplayOutcome(
            OUTCOME_FAILED,
            "capsule records no finding.json — its static evidence cannot be "
            "re-verified",
            None, None, None,
        )
    recorded_type = str(finding.get("type") or "")
    recorded_contract = str(finding.get("contract_id") or "")
    evidence_type = str(manifest.get("evidence_type") or "").strip().lower()

    snippets = read_static_snippets(unit.zip_path)
    if snippets:
        for rel, content in snippets:
            key = resolve_recorded_path(head, rel)
            if key is None:
                return ReplayOutcome(
                    OUTCOME_FAILED,
                    f"recorded static evidence path {rel} is gone from head ref "
                    f"{head_ref} — the recorded snippet no longer exists at head",
                    None, None, None,
                )
            if _normalize_snippet(recorded_path_content(head, key)) != _normalize_snippet(
                content
            ):
                return ReplayOutcome(
                    OUTCOME_FAILED,
                    f"recorded static evidence snippet {rel} no longer matches the "
                    f"recorded content at head ref {head_ref}",
                    None, None, None,
                )
        return ReplayOutcome(
            OUTCOME_SAME,
            f"{STATIC_VERIFIED_NOTE} — {len(snippets)} recorded snippet(s) present "
            f"with recorded content at head ref {head_ref}",
            None, None, None,
        )

    for recorded in recorded_static_paths(finding):
        if resolve_recorded_path(head, recorded) is None:
            return ReplayOutcome(
                OUTCOME_FAILED,
                f"recorded static evidence path {recorded} is gone from head ref "
                f"{head_ref} — the recorded snippet no longer exists at head",
                None, None, None,
            )

    fresh, error = rederive_static_findings(evidence_type, contract, base, head)
    if error:
        return ReplayOutcome(OUTCOME_FAILED, error, None, None, None)
    candidates = [f for f in fresh if f.get("contract_id") == recorded_contract]
    if not candidates:
        return ReplayOutcome(
            OUTCOME_FAILED,
            f"recorded static evidence for {recorded_contract or '<none>'} no longer "
            f"re-verifies at head ref {head_ref}: the deterministic checkers produce "
            "no violation for the contract at head",
            None, None, None,
        )
    exact = [f for f in candidates if str(f.get("type") or "") == recorded_type]
    if exact:
        return ReplayOutcome(
            OUTCOME_SAME,
            f"{STATIC_VERIFIED_NOTE} — the deterministic checker re-derived the "
            f"recorded finding {recorded_contract}/{recorded_type} at head ref {head_ref}",
            None, None, None,
        )
    if "probe" in evidence_type:
        matched = candidates[0]
        return ReplayOutcome(
            OUTCOME_SAME,
            f"{STATIC_VERIFIED_NOTE} — the deterministic event check re-derived the "
            f"recorded probe claim for {recorded_contract} at head ref {head_ref} "
            f"({matched.get('type')}: {str(matched.get('description'))[:100]})",
            None, None, None,
        )
    fresh_types = ", ".join(sorted({str(f.get("type") or "") for f in candidates}))
    return ReplayOutcome(
        OUTCOME_FAILED,
        f"recorded static evidence for {recorded_contract} ({recorded_type}) no longer "
        f"re-verifies at head ref {head_ref}: the checker now reports "
        f"{fresh_types or 'nothing'}",
        None, None, None,
    )


def run_static_reverification(
    unit: CapsuleUnit,
    manifest: dict[str, Any],
    finding: dict[str, Any] | None,
    contract: dict[str, Any] | None,
    repo_dir: Path,
) -> ReplayOutcome:
    """Tier-2 replay: re-verify recorded static evidence in the temp worktree.

    Checks out the recorded base and head refs (both already known to exist
    in the worktree), snapshots each side's sources, and re-verifies the
    recorded evidence against the head tree.
    """
    base_ref = unit.base_ref
    head_ref = unit.head_ref
    if not head_ref:
        return ReplayOutcome(
            OUTCOME_FAILED,
            "capsule records no head ref — static evidence cannot be re-verified",
            None, None, None,
        )
    if not base_ref:
        return ReplayOutcome(
            OUTCOME_FAILED,
            "capsule records no base ref — the recorded base/head evidence claim "
            "cannot be re-verified",
            None, None, None,
        )
    error = checkout_worktree_ref(repo_dir, base_ref)
    if error:
        return ReplayOutcome(
            OUTCOME_ENV,
            f"cannot check out recorded base ref {base_ref} in the replay worktree: {error}",
            None, None, None,
        )
    base = snapshot_worktree_sources(repo_dir)
    error = checkout_worktree_ref(repo_dir, head_ref)
    if error:
        return ReplayOutcome(
            OUTCOME_ENV,
            f"cannot check out recorded head ref {head_ref} in the replay worktree: {error}",
            None, None, None,
        )
    head = snapshot_worktree_sources(repo_dir)
    return classify_static_replay(unit, manifest, finding, contract, base, head)


def probe_environment() -> dict[str, Any]:
    """Probe the tools a real replay needs (never fabricates availability)."""
    def which(name: str) -> str | None:
        found = shutil.which(name)
        return found if found else None

    java_version = ""
    java = which("java")
    if java:
        try:
            java_version = subprocess.run(
                [java, "-version"], capture_output=True, text=True, timeout=30,
                check=False,
            ).stderr.strip().splitlines()[0]
        except (OSError, subprocess.TimeoutExpired, IndexError):
            java_version = ""
    maven_dist = Path.home() / ".m2" / "wrapper" / "dists"
    return {
        "python": sys.executable,
        "git": which("git"),
        "pwsh": which("pwsh"),
        "bash": which("bash"),
        "java": java,
        "java_version": java_version,
        "maven_dist_cache": str(maven_dist) if maven_dist.is_dir() else "",
    }


def prepare_temp_worktree(
    repo_root: Path, refs: frozenset[str], work_root: Path,
) -> dict[str, Any]:
    """Prepare a throwaway git repo whose root is the demo project.

    The capsule run scripts expect a git repository whose ROOT is the Maven
    project (mvnw at the repo root), while in this repo the demo project
    lives at demo/spring-backend. We clone the repo into a temp directory
    (read-only with respect to the real repo) and rebuild each needed ref
    with git subtree split --prefix=demo/spring-backend, retagging it with
    its original name, so the temp repo's root IS the demo project and the
    capsule run scripts' git checkout <ref> + ./mvnw work unchanged. If
    subtree split is unavailable, the fallback rebuilds the same refs from
    git archive content (byte-identical project trees, synthetic commits).
    """
    clone = work_root / "src"
    result = subprocess.run(
        ["git", "clone", "--quiet", "--no-checkout", "--", str(repo_root), str(clone)],
        capture_output=True, text=True, timeout=600, check=False,
    )
    if result.returncode != 0:
        return {
            "repo": None,
            "mechanism": "none",
            "refs": {},
            "error": result.stderr.strip()[:400],
        }
    try:
        return _prepare_via_subtree(clone, refs)
    except (OSError, subprocess.SubprocessError, tarfile.TarError):
        return _prepare_via_archive(clone, refs)


def _prepare_via_subtree(clone: Path, refs: frozenset[str]) -> dict[str, Any]:
    """Rebuild refs via git subtree split (real per-commit history)."""
    resolved: dict[str, bool] = {}
    for ref in sorted(refs):
        split = subprocess.run(
            [
                "git", "-C", str(clone), "subtree", "split",
                "--prefix=demo/spring-backend", ref,
            ],
            capture_output=True, text=True, timeout=900, check=False,
        )
        if split.returncode != 0:
            raise subprocess.SubprocessError(
                f"subtree split failed for {ref}: {split.stderr.strip()[:200]}"
            )
        commit = split.stdout.strip().splitlines()[-1].strip()
        tagged = subprocess.run(
            ["git", "-C", str(clone), "tag", "-f", ref, commit],
            capture_output=True, text=True, timeout=120, check=False,
        )
        if tagged.returncode != 0:
            raise subprocess.SubprocessError(
                f"tagging {ref} failed: {tagged.stderr.strip()[:200]}"
            )
        resolved[ref] = True
    first = sorted(refs)[0]
    subprocess.run(
        ["git", "-C", str(clone), "checkout", "--quiet", "-f", first],
        capture_output=True, text=True, timeout=600, check=False,
    )
    return {"repo": clone, "mechanism": "subtree-split", "refs": resolved, "error": ""}


def _prepare_via_archive(clone: Path, refs: frozenset[str]) -> dict[str, Any]:
    """Fallback: rebuild refs from git archive content, synthetic commits."""
    synthetic = clone.parent / "synthetic"
    synthetic.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        ["git", "-C", str(synthetic), "init", "--quiet", "-b", "main"],
        capture_output=True, text=True, timeout=120, check=False,
    )
    resolved: dict[str, bool] = {}
    for ref in sorted(refs):
        archive = subprocess.run(
            ["git", "-C", str(clone), "archive", "--format=tar", ref, "demo/spring-backend"],
            capture_output=True, timeout=900, check=False,
        )
        if archive.returncode != 0:
            resolved[ref] = False
            continue
        for entry in synthetic.iterdir():
            if entry.name != ".git":
                if entry.is_dir():
                    shutil.rmtree(entry, ignore_errors=True)
                else:
                    entry.unlink(missing_ok=True)
        prefix = "demo/spring-backend/"
        with tarfile.open(fileobj=io.BytesIO(archive.stdout), mode="r:") as tar:
            for member in tar.getmembers():
                if not member.name.startswith(prefix):
                    continue
                relative = member.name[len(prefix):]
                if not relative or member.isdir():
                    continue
                target = synthetic / relative
                target.parent.mkdir(parents=True, exist_ok=True)
                extracted = tar.extractfile(member)
                if extracted is not None:
                    target.write_bytes(extracted.read())
        subprocess.run(
            ["git", "-C", str(synthetic), "add", "-A"],
            capture_output=True, text=True, timeout=300, check=False,
        )
        committed = subprocess.run(
            [
                "git", "-C", str(synthetic), "-c", "user.name=bench-replay",
                "-c", "user.email=bench-replay@specproof.invalid",
                "commit", "--quiet", "-m", f"archive of {ref}",
            ],
            capture_output=True, text=True, timeout=300, check=False,
        )
        if committed.returncode != 0:
            resolved[ref] = False
            continue
        subprocess.run(
            ["git", "-C", str(synthetic), "tag", "-f", ref, "HEAD"],
            capture_output=True, text=True, timeout=120, check=False,
        )
        resolved[ref] = True
    subprocess.run(
        ["git", "-C", str(synthetic), "checkout", "--quiet", "-f", sorted(refs)[0]],
        capture_output=True, text=True, timeout=600, check=False,
    )
    return {
        "repo": synthetic,
        "mechanism": "archive-synthetic",
        "refs": resolved,
        "error": "",
    }


def extract_via_replay_cli(
    python: str, repo_root: Path, zip_path: Path, out_dir: Path,
) -> tuple[bool, str]:
    """Run the existing replay CLI to extract the capsule and write its report."""
    out_dir.mkdir(parents=True, exist_ok=True)
    result = subprocess.run(
        [
            python, "-m", "cli.specproof.main", "replay",
            str(zip_path), "--output-dir", str(out_dir),
        ],
        cwd=repo_root,
        capture_output=True,
        text=True,
        timeout=CLI_TIMEOUT_S,
        check=False,
    )
    return result.returncode == 0, (result.stdout + "\n" + result.stderr).strip()


def execute_run_script(extracted_dir: Path, repo: Path, timeout: float) -> RunResult:
    """Execute the capsule's own replay script against the temp worktree.

    Windows-native first: run.ps1 via pwsh; otherwise run.sh via bash.
    The scripts are executed unmodified, exactly as generated.
    """
    script_ps1 = extracted_dir / "run.ps1"
    script_sh = extracted_dir / "run.sh"
    pwsh = shutil.which("pwsh")
    bash = shutil.which("bash")
    if script_ps1.exists() and pwsh:
        command = [
            pwsh, "-NoProfile", "-NonInteractive", "-ExecutionPolicy", "Bypass",
            "-File", str(script_ps1), "-RepoDir", str(repo),
        ]
    elif script_sh.exists() and bash:
        command = [bash, str(script_sh), str(repo)]
    elif script_ps1.exists() or script_sh.exists():
        return RunResult(
            exit_code=-1, stdout="", stderr="", timed_out=False,
            error="no pwsh/bash executor available for the capsule run script",
        )
    else:
        return RunResult(
            exit_code=-1, stdout="", stderr="", timed_out=False,
            error="capsule carries no run.sh / run.ps1 replay script",
        )
    try:
        result = subprocess.run(
            command, cwd=extracted_dir, capture_output=True, text=True,
            timeout=timeout, check=False,
        )
        return RunResult(
            exit_code=result.returncode,
            stdout=result.stdout,
            stderr=result.stderr,
            timed_out=False,
            error="",
        )
    except subprocess.TimeoutExpired:
        return RunResult(exit_code=-1, stdout="", stderr="", timed_out=True, error="")
    except OSError as exc:
        return RunResult(
            exit_code=-1, stdout="", stderr="", timed_out=False, error=str(exc)
        )


def check_generated_test_presence(repo: Path) -> dict[str, bool]:
    """Whether the capsule's generated test landed where Maven compiles.

    The generated run scripts copy generated-tests/* into <repo>/src/test/;
    Maven compiles only src/test/java/**. Both facts are recorded honestly.
    """
    def contains_specproof_generated(directory: Path) -> bool:
        if not directory.is_dir():
            return False
        return any(path.is_file() for path in directory.rglob("SpecProofGeneratedTest*.java"))

    return {
        "in_test_java": contains_specproof_generated(repo / "src" / "test" / "java"),
        "in_test_root": contains_specproof_generated(repo / "src" / "test"),
    }


