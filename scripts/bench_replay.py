def run_bench(args: argparse.Namespace) -> dict[str, Any]:
    """Run the batch replay and return the results document."""
    capsules_dir = Path(args.capsules_dir)
    repo_root = Path(args.repo)
    environment = probe_environment()

    units, inventory = enumerate_capsules(capsules_dir, None)
    if args.limit is not None:
        units = units[: max(0, args.limit)]

    # Evidence gate first: only consistent capsules proceed to execution.
    evidence_by_unit: dict[str, EvidenceReport] = {}
    manifest_by_unit: dict[str, dict[str, Any] | None] = {}
    finding_by_unit: dict[str, dict[str, Any] | None] = {}
    contract_by_unit: dict[str, dict[str, Any] | None] = {}
    for unit in units:
        manifest = read_zip_json(unit.zip_path, "manifest.json") if unit.zip_path else None
        manifest_by_unit[unit.name] = manifest
        finding_by_unit[unit.name] = (
            read_zip_json(unit.zip_path, "finding.json") if unit.zip_path else None
        )
        contract_by_unit[unit.name] = (
            read_zip_json(unit.zip_path, "contract.json") if unit.zip_path else None
        )
        evidence_by_unit[unit.name] = verify_evidence(unit)

    runnable = [
        unit for unit in units
        if not evidence_by_unit[unit.name].inconsistent and unit.zip_path is not None
    ]
    refs = frozenset(
        ref for unit in runnable
        for ref in (unit.base_ref, unit.head_ref) if ref
    )

    work_root = Path(tempfile.mkdtemp(prefix="specproof-bench-replay-"))
    worktree: dict[str, Any] = {
        "repo": None, "mechanism": "none", "refs": {}, "error": "",
    }
    prep_error = ""
    executor_missing = ""
    if runnable:
        if not environment["pwsh"] and not environment["bash"]:
            executor_missing = "no capsule run-script executor (pwsh/bash) available"
        elif not environment["git"]:
            executor_missing = "git is not available — a temp replay worktree cannot be prepared"
        else:
            worktree = prepare_temp_worktree(repo_root, refs, work_root)
            if worktree["repo"] is None:
                prep_error = worktree.get("error") or "temp worktree preparation failed"

    entries: list[dict[str, Any]] = []
    repo_dir: Path | None = worktree["repo"]
    for index, unit in enumerate(units, start=1):
        entry = build_unit_entry(unit, manifest_by_unit[unit.name])
        evidence = evidence_by_unit[unit.name]
        entry["evidence_problems"] = list(evidence.problems)
        duration_s = 0.0
        if evidence.inconsistent:
            outcome = ReplayOutcome(
                OUTCOME_EVIDENCE, "; ".join(evidence.problems), None, None, None,
            )
        elif executor_missing:
            outcome = ReplayOutcome(OUTCOME_ENV, executor_missing, None, None, None)
        elif prep_error:
            outcome = ReplayOutcome(
                OUTCOME_ENV, f"temp worktree preparation failed: {prep_error}",
                None, None, None,
            )
        else:
            assert repo_dir is not None
            worktree_refs: dict[str, bool] = worktree["refs"]
            missing_refs = [
                ref for ref in (unit.base_ref, unit.head_ref)
                if ref and not worktree_refs.get(ref, False)
            ]
            if missing_refs:
                outcome = ReplayOutcome(
                    OUTCOME_ENV,
                    f"recorded ref(s) {', '.join(missing_refs)} not available in the repo",
                    None, None, None,
                )
            else:
                extracted = work_root / "extracted" / unit.name
                ok, cli_output = extract_via_replay_cli(
                    sys.executable, repo_root, unit.zip_path or Path(), extracted,
                )
                entry["replay_cli"] = {
                    "ok": ok,
                    "report": str(extracted / "replay-report.json"),
                    "output_tail": cli_output.strip().splitlines()[-5:],
                }
                if not ok:
                    cli_tail = " | ".join(cli_output.strip().splitlines()[-8:])
                    if "digest mismatch" in cli_output or "Corrupt capsule" in cli_output:
                        outcome = ReplayOutcome(
                            OUTCOME_EVIDENCE,
                            f"existing replay path rejected the capsule: {cli_tail}",
                            None, None, None,
                        )
                    else:
                        outcome = ReplayOutcome(
                            OUTCOME_FAILED,
                            f"existing replay path failed: {cli_tail}",
                            None, None, None,
                        )
                else:
                    manifest = json.loads(
                        (extracted / "manifest.json").read_text(encoding="utf-8")
                    )
                    expected = expected_verdict_for(manifest)
                    entry["expected_verdict"] = expected
                    if is_static_only_capsule(manifest):
                        outcome = run_static_reverification(
                            unit,
                            manifest,
                            finding_by_unit[unit.name],
                            contract_by_unit[unit.name],
                            repo_dir,
                        )
                        entry["replay_mode"] = "static_reverify"
                        entry["static_verified"] = outcome.outcome == OUTCOME_SAME
                    else:
                        entry["replay_mode"] = "runtime"
                        entry["static_verified"] = False
                        unit_start = time.monotonic()
                        run = execute_run_script(extracted, repo_dir, args.timeout)
                        duration_s = time.monotonic() - unit_start
                        outcome = classify_replay(expected, run)
                        entry["run_exit_code"] = run.exit_code
                        entry["timed_out"] = run.timed_out
                        entry["run_output_tail"] = (
                            (run.stdout + "\n" + run.stderr).strip().splitlines()[-8:]
                        )
                        generated_test = check_generated_test_presence(repo_dir)
                        entry["generated_test"] = generated_test
                        if (
                            outcome.outcome == OUTCOME_FAILED
                            and generated_test["in_test_root"]
                            and not generated_test["in_test_java"]
                        ):
                            outcome = ReplayOutcome(
                                outcome.outcome,
                                outcome.reason + " — root cause: the capsule's generated "
                                "test was injected into src/test/ (outside Maven's test "
                                "source root src/test/java/) and was never compiled",
                                outcome.verdict,
                                outcome.base_exit,
                                outcome.head_exit,
                            )
        entry["outcome"] = outcome.outcome
        entry["reason"] = outcome.reason
        entry["verdict"] = outcome.verdict
        entry["base_exit"] = outcome.base_exit
        entry["head_exit"] = outcome.head_exit
        entry["duration_s"] = round(duration_s, 2)
        entries.append(entry)
        print(
            f"[{index}/{len(units)}] {unit.name} -> {outcome.outcome}"
            f"{' (' + outcome.verdict + ')' if outcome.verdict else ''}",
            flush=True,
        )

    totals = dict.fromkeys(OUTCOMES, 0)
    static_verified = 0
    for entry in entries:
        totals[entry["outcome"]] += 1
        if entry.get("static_verified"):
            static_verified += 1
    enumerated = len(entries)
    rate = totals[OUTCOME_SAME] / enumerated if enumerated else 0.0
    executed = enumerated - totals[OUTCOME_ENV]
    rate_excluding_env = totals[OUTCOME_SAME] / executed if executed else 0.0
    kept = args.keep_worktree
    if not kept:
        shutil.rmtree(work_root, ignore_errors=True)
    results: dict[str, Any] = {
        "generated_at": datetime.now(UTC).isoformat(),
        "tool": "scripts/bench_replay.py",
        "repo_root": str(repo_root.resolve()),
        "capsules_dir": str(capsules_dir.resolve()),
        "limit": args.limit,
        "worktree": {
            "mechanism": worktree["mechanism"],
            "path": str(worktree["repo"]) if kept and worktree["repo"] else "",
            "prep_error": prep_error,
        },
        "environment": environment,
        "store": inventory,
        "totals": {
            "enumerated": enumerated,
            **totals,
            "static_verified": static_verified,
            "success_rate": round(rate, 4),
            "success_rate_excluding_env_mismatch": round(rate_excluding_env, 4),
            "gate_replay_success_rate_095": rate >= GATE_REPLAY_SUCCESS_RATE,
        },
        "capsules": entries,
    }
    write_reports(results, Path(args.output_json), Path(args.output_md))
    return results


