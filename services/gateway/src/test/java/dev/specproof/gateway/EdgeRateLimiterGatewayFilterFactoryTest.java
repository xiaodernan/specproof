package dev.specproof.gateway;

import static org.assertj.core.api.Assertions.assertThat;

import java.time.Duration;
import java.util.concurrent.atomic.AtomicInteger;

import org.junit.jupiter.api.Test;
import org.springframework.cloud.gateway.filter.GatewayFilter;
import org.springframework.cloud.gateway.filter.GatewayFilterChain;
import org.springframework.http.HttpStatus;
import org.springframework.mock.http.server.reactive.MockServerHttpRequest;
import org.springframework.mock.http.server.reactive.MockServerHttpResponse;
import org.springframework.mock.web.server.MockServerWebExchange;
import org.springframework.web.server.ServerWebExchange;

import dev.specproof.gateway.filter.EdgeRateLimiterGatewayFilterFactory;
import dev.specproof.gateway.filter.EdgeRequestIdGlobalFilter;

import io.micrometer.core.instrument.simple.SimpleMeterRegistry;

import reactor.core.publisher.Mono;

/**
 * The edge's ingress rate limiter, tested without any live upstream.
 *
 * <p>All three tests drive the production {@link EdgeRateLimiterGatewayFilterFactory}
 * directly; the YAML-declared bucket (50 permits per second) is exercised by
 * the arguments the test applies, never re-typed from application.yml.
 */
class EdgeRateLimiterGatewayFilterFactoryTest {

    private static EdgeRateLimiterGatewayFilterFactory.Config config(int limit) {
        EdgeRateLimiterGatewayFilterFactory.Config config =
                new EdgeRateLimiterGatewayFilterFactory.Config();
        config.setName("specproof-edge-public-test");
        config.setLimitForPeriod(limit);
        config.setLimitRefreshPeriod(Duration.ofSeconds(1));
        config.setTimeoutDuration(Duration.ZERO);
        return config;
    }

    private static ServerWebExchange newExchange() {
        MockServerHttpRequest request = MockServerHttpRequest
                .get("http://edge.test/api/v1/anything")
                .build();
        return MockServerWebExchange.builder(request).build();
    }

    private static GatewayFilterChain okChain(AtomicInteger upstreamCalls) {
        return exchange -> {
            upstreamCalls.incrementAndGet();
            exchange.getResponse().setStatusCode(HttpStatus.OK);
            return exchange.getResponse().setComplete();
        };
    }

    @Test
    void theBucketAdmitsUpToTheConfiguredLimitWithoutTouchingItEarly() {
        EdgeRateLimiterGatewayFilterFactory factory =
                new EdgeRateLimiterGatewayFilterFactory(new SimpleMeterRegistry());
        GatewayFilter filter = factory.apply(config(3));

        AtomicInteger upstreamCalls = new AtomicInteger();
        for (int i = 0; i < 3; i++) {
            ServerWebExchange exchange = newExchange();
            new EdgeRequestIdGlobalFilter()
                    .filter(exchange, mutated ->
                            filter.filter(mutated, okChain(upstreamCalls)))
                    .block();
            assertThat(exchange.getResponse().getStatusCode())
                    .isEqualTo(HttpStatus.OK);
        }
        assertThat(upstreamCalls.get()).isEqualTo(3);
    }

    @Test
    void anExhaustedBucketAnswers429WithRequestIdAndRetryAfter() {
        EdgeRateLimiterGatewayFilterFactory factory =
                new EdgeRateLimiterGatewayFilterFactory(new SimpleMeterRegistry());
        GatewayFilter filter = factory.apply(config(2));

        AtomicInteger upstreamCalls = new AtomicInteger();
        ServerWebExchange first = newExchange();
        ServerWebExchange second = newExchange();
        ServerWebExchange third = newExchange();
        new EdgeRequestIdGlobalFilter()
                .filter(first, mutated -> filter.filter(mutated, okChain(upstreamCalls)))
                .block();
        new EdgeRequestIdGlobalFilter()
                .filter(second, mutated -> filter.filter(mutated, okChain(upstreamCalls)))
                .block();
        new EdgeRequestIdGlobalFilter()
                .filter(third, mutated -> filter.filter(mutated, okChain(upstreamCalls)))
                .block();

        assertThat(upstreamCalls.get()).isEqualTo(2);
        assertThat(third.getResponse().getStatusCode())
                .isEqualTo(HttpStatus.TOO_MANY_REQUESTS);
        assertThat(third.getResponse().getHeaders().getFirst("Retry-After"))
                .isEqualTo("1");
        assertThat(third.getResponse()).isInstanceOf(MockServerHttpResponse.class);
        String body = ((MockServerHttpResponse) third.getResponse())
                .getBodyAsString().block();
        assertThat(body).contains("\"rate_limited\"");
        // the request id is generated by the global filter before the limiter runs,
        // so the edge's own 429 carries the same id its 503s do
        assertThat(body).containsPattern("\"request_id\":\"[0-9a-f]{16}\"");
    }

    @Test
    void rejectionsAreCountedThroughMicrometer() {
        SimpleMeterRegistry meterRegistry = new SimpleMeterRegistry();
        EdgeRateLimiterGatewayFilterFactory factory =
                new EdgeRateLimiterGatewayFilterFactory(meterRegistry);
        GatewayFilter filter = factory.apply(config(1));

        AtomicInteger upstreamCalls = new AtomicInteger();
        ServerWebExchange ok = newExchange();
        ServerWebExchange denied = newExchange();
        filter.filter(ok, okChain(upstreamCalls)).block();
        filter.filter(denied, okChain(upstreamCalls)).block();

        assertThat(meterRegistry.get("specproof.gateway.rate.limited")
                .tag("limiter", "specproof-edge-public-test")
                .counter()
                .count())
                .isEqualTo(1.0);

        // the tagged binder publishes the limiter's own gauges, tagged by name
        assertThat(meterRegistry.get("resilience4j.ratelimiter.available.permissions")
                .tag("name", "specproof-edge-public-test")
                .gauge()
                .value())
                .isEqualTo(0.0);
    }
}
