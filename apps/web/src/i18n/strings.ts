/** Locale outside React — the render-time gloss helpers read this. */
export function storedLocale(): Locale {
  try {
    const stored = globalThis.localStorage?.getItem("specproof_locale");
    if (stored === "zh" || stored === "en") return stored;
  } catch {
    // localStorage unavailable (SSR / tests without jsdom) — fall through
  }
  const nav = globalThis.navigator?.language || "";
  return nav.toLowerCase().startsWith("zh") ? "zh" : "en";
}

