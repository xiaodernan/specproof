"""The signing-key generator, end to end through the product's own signer.

``scripts/generate_signing_key.py`` is the supported way to make a
``SPECPROOF_SIGNING_KEY``. These legs prove the key it generates is a real
Ed25519 seed, that the file mode is restricted on POSIX (and not
over-claimed on Windows), that overwriting an existing key requires an
explicit ``--force``, and — the leg that matters — that a key generated by
the script drops straight into the product's signer: ``evidence/signing.py``
signs a statement and ``verify_statement`` accepts it, under the public key
the script prints.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))
sys.path.insert(0, str(ROOT))

import generate_signing_key  # noqa: E402

from evidence import signing  # noqa: E402


def _run(argv: list[str]) -> int:
    old_argv = list(sys.argv)
    sys.argv = ["generate_signing_key.py", *argv]
    try:
        return generate_signing_key.main()
    finally:
        sys.argv = old_argv


def test_stdout_mode_prints_only_the_seed_and_the_public_key_is_on_stderr(
    capsys: pytest.CaptureFixture[str],
) -> None:
    assert _run([]) == 0
    captured = capsys.readouterr()
    out, err = captured.out, captured.err
    seed_line = out.strip()
    assert len(seed_line) == 64
    int(seed_line, 16)  # raises on non-hex
    assert "public key" in err
    assert seed_line not in err, "the seed must not ride stderr with the public key"


def test_two_runs_produce_different_keys(capsys: pytest.CaptureFixture[str]) -> None:
    _run([])
    first = capsys.readouterr().out.strip()
    _run([])
    second = capsys.readouterr().out.strip()
    assert first != second


def test_generated_key_drops_into_the_products_signer_and_verifies(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    seed = b"\x01" * 32
    key_path = tmp_path / "seed.hex"
    key_path.write_text(seed.hex() + "\n", encoding="utf-8")
    monkeypatch.setenv("SPECPROOF_SIGNING_KEY_FILE", str(key_path))
    monkeypatch.delenv("SPECPROOF_SIGNING_KEY", raising=False)

    from cryptography.hazmat.primitives.asymmetric.ed25519 import (
        Ed25519PrivateKey,
        Ed25519PublicKey,
    )

    assert isinstance(Ed25519PrivateKey.from_private_bytes(seed), Ed25519PrivateKey)
    pub = signing.public_key_hex()
    assert pub == generate_signing_key.public_key_hex(seed)

    statement = signing.sign_statement({"hello": "world"})
    assert signing.verify_statement(statement, pub) is True
    assert signing.verify_statement(statement, "00" * 32) is False
    assert isinstance(
        Ed25519PublicKey.from_public_bytes(bytes.fromhex(pub)),
        Ed25519PublicKey,
    )


def test_write_mode_creates_the_file_and_refuses_to_overwrite_without_force(
    tmp_path: Path,
    capsys: pytest.CaptureFixture[str],
) -> None:
    target = tmp_path / "seed.hex"

    assert _run(["--output", str(target)]) == 0
    assert target.exists()
    content = target.read_text(encoding="utf-8").strip()
    assert len(content) == 64
    int(content, 16)

    with pytest.raises(SystemExit) as excinfo:
        _run(["--output", str(target)])
    assert "--force" in str(excinfo.value)

    capsys.readouterr()  # drain

    assert _run(["--output", str(target), "--force"]) == 0
    refreshed = target.read_text(encoding="utf-8").strip()
    assert len(refreshed) == 64


@pytest.mark.skipif(os.name != "posix", reason="POSIX mode bits are advisory on Windows")
def test_written_key_file_is_0600(tmp_path: Path) -> None:
    target = tmp_path / "seed.hex"
    assert _run(["--output", str(target)]) == 0
    assert (target.stat().st_mode & 0o777) == 0o600
